const pct = v => Number.isFinite(v) ? String(+(v * 100).toFixed(4)) : '';
const num = (v, d = 1) => Number.isFinite(v) ? v.toFixed(d) : '';

// ------------------------------------------------------------- seeds
function seedList() {
  const list = h('div', { class: 'list' });
  for (const s of allSeeds(defaults)) {
    const yc = SEGMENTS.map(k => `${SEG_LABELS[k].split(' ')[0]} ${s.yield_change[k] >= 0 ? '+' : ''}${pct(s.yield_change[k] || 0)}%`).join(' · ');
    list.append(h('div', { class: 'item' + (seedForm.id === s.id ? ' active' : '') },
      h('div', {}, h('div', { class: 'name' }, s.label, s.official ? '' : ' ✦'), h('div', { class: 'meta' }, yc)),
      h('span', { class: 'spacer' }),
      h('button', { class: 'btn small', onClick: () => { startSeedFrom(s, true); } }, s.official ? 'Start from' : 'Edit'),
      s.official ? null : h('button', { class: 'btn small danger', onClick: () => { if (confirm(`Delete seed "${s.label}"?`)) { deleteSeed(s.id); if (seedForm.id === s.id) resetSeedForm(); renderAll(); toast('Seed deleted'); } } }, 'Delete')));
  }
  return list;
}
function baseDefault() { return defaults.seeds.find(s => s.id === 's28') || defaults.seeds[defaults.seeds.length - 1]; }
// autoLabel: the name was generated by the form (helpers, "Start from"), so the next helper may
// replace it; a name the user typed is never overwritten.
function resetSeedForm() { const b = baseDefault(); seedForm = { id: null, label: '', autoLabel: true, year: '2030', yield_change: { ...b.yield_change }, baseId: b.id, source: `copied from ${b.label}` }; }
function startSeedFrom(s, edit) {
  if (edit && !s.official) seedForm = { id: s.id, label: s.label, autoLabel: false, year: s.year, yield_change: { ...s.yield_change }, baseId: s.id, source: `saved seed "${s.label}"` };
  else seedForm = { id: null, label: `${s.official ? s.year : s.label} base, modified`, autoLabel: true, year: s.year, yield_change: { ...s.yield_change }, baseId: s.id, source: `copied from ${s.label}` };
  renderSeedForm();
  els.seedList.replaceChildren(seedList());
}
const yieldsText = yc => SEGMENTS.map(k => `${SEG_LABELS[k].split(' ')[0]} ${yc[k] >= 0 ? '+' : ''}${pct(yc[k])}%`).join(' · ');
const signed = x => (x >= 0 ? '+' : '') + String(x);
function renderSeedForm() {
  const f = seedForm;
  const name = h('input', { type: 'text', value: f.label, placeholder: 'e.g. 2030 Seed', maxlength: 80 });
  name.addEventListener('input', () => { f.label = name.value; f.autoLabel = name.value.trim() === ''; });
  const year = h('input', { type: 'text', value: f.year, placeholder: '2030', maxlength: 12, onInput: e => { f.year = e.target.value; } });
  const sourceLine = h('div', { class: 'seg-preview' });
  const setSource = () => { sourceLine.replaceChildren('Yields below: ', h('b', {}, f.source || 'typed by hand')); };
  const segInputs = {}, segErr = {};
  const msgs = h('div', { class: 'warn-list' });
  const showProblems = () => {
    const p = yieldProblems(f.yield_change);
    msgs.replaceChildren(...p.errors.map(e => h('div', { class: 'note err' }, e)), ...p.warnings.map(w => h('div', { class: 'note' }, w)));
    return p;
  };
  const segGrid = h('div', { class: 'seg-grid' }, SEGMENTS.map(k => {
    const inp = h('input', { type: 'text', inputmode: 'decimal', value: pct(f.yield_change[k] ?? 0), 'aria-label': `${SEG_LABELS[k]} yield change (%)` });
    const err = h('span', { class: 'err-msg' });
    inp.addEventListener('input', () => {
      const v = parseNum(inp.value);
      const bad = !Number.isFinite(v);
      inp.classList.toggle('invalid', bad);
      err.textContent = bad ? (inp.value.trim() === '' ? 'Enter a number' : 'Not a number (use 10.5 or 10,5)') : '';
      f.yield_change[k] = bad ? NaN : Number((v / 100).toFixed(10)); // typed % to a clean fraction (see scenarios.js)
      f.source = 'edited by hand';
      if (f.autoLabel) { const b = findSeed(defaults, f.baseId); f.label = `${b ? (b.official ? b.year : b.label) : 'Custom'} base, custom yields`; name.value = f.label; }
      setSource(); showProblems();
    });
    segInputs[k] = inp; segErr[k] = err;
    return h('div', { class: 'field' }, h('label', {}, SEG_LABELS[k]), inp, err, h('span', { class: 'hint' }, 'yield change, %'));
  }));
  const refreshSeg = () => SEGMENTS.forEach(k => { segInputs[k].value = pct(f.yield_change[k]); segInputs[k].classList.remove('invalid'); segErr[k].textContent = ''; });
  const baseSel = h('select', { 'aria-label': 'Start from seed' }, allSeeds(defaults).map(s => h('option', { value: s.id, selected: s.id === f.baseId ? true : null }, s.label)));
  const xMult = h('input', { type: 'text', inputmode: 'decimal', value: '10', 'aria-label': 'Raise yield by X percent' });
  const xAdd = h('input', { type: 'text', inputmode: 'decimal', value: '10', 'aria-label': 'Add X percentage points' });
  const prevMult = h('div', { class: 'seg-preview' }), prevAdd = h('div', { class: 'seg-preview' });
  const helperResult = (kind) => {
    const base = findSeed(defaults, baseSel.value);
    const x = parseNum((kind === 'mult' ? xMult : xAdd).value);
    if (!base) return { error: 'Pick a seed to start from.' };
    if (!Number.isFinite(x)) return { error: 'X is not a number (use 10, 10.5 or 10,5).' };
    const yc = kind === 'mult' ? raiseYieldMultiplicative(base.yield_change, x / 100) : raiseYieldAdditive(base.yield_change, x / 100);
    const p = yieldProblems(yc);
    const baseName = base.official ? base.year : base.label;
    return { base, x, yc, error: p.errors[0], name: kind === 'mult' ? `${baseName} base ${signed(x)}% yield` : `${baseName} base ${signed(x)} pp yield`,
      source: kind === 'mult' ? `${base.label} with ${signed(x)}% yield in every segment, multiplicative: (1 + y) x ${+(1 + x / 100).toFixed(4)} - 1` : `${base.label} ${signed(x)} percentage points in every segment` };
  };
  const refreshPreviews = () => {
    for (const [kind, el] of [['mult', prevMult], ['add', prevAdd]]) {
      const r = helperResult(kind);
      el.replaceChildren(r.error && !r.yc ? h('span', { class: 'err-msg' }, r.error) : h('span', {}, 'Gives: ', h('b', {}, yieldsText(r.yc)), r.error ? h('span', { class: 'err-msg' }, ' ' + r.error) : ''));
    }
  };
  [xMult, xAdd].forEach(i => i.addEventListener('input', refreshPreviews));
  baseSel.addEventListener('change', refreshPreviews);
  const apply = kind => {
    const r = helperResult(kind);
    if (r.error) { toast(r.error); return; }
    f.baseId = r.base.id; f.yield_change = r.yc; f.source = r.source;
    if (f.autoLabel || !f.label.trim()) { f.label = r.name; f.autoLabel = true; name.value = f.label; }
    refreshSeg(); setSource(); showProblems(); markDirty('seed');
    toast(`Yields set from ${r.base.label}: ${yieldsText(r.yc)}`);
  };
  const save = () => {
    const label = f.label.trim();
    if (!label) { toast('Give the seed a name'); name.focus(); return; }
    const clash = allSeeds(defaults).find(s => s.id !== f.id && s.label.trim().toLowerCase() === label.toLowerCase());
    if (clash) { toast(`A seed called "${clash.label}" already exists; choose another name`); name.focus(); return; }
    const p = showProblems();
    if (p.errors.length) { toast('Fix the yield values first'); return; }
    const s = saveSeed({ id: f.id, label, year: String(f.year || '').trim(), yield_change: { ...f.yield_change } });
    seedForm.id = s.id; seedForm.label = s.label; seedForm.autoLabel = false; markClean('seed');
    toast(`Seed "${s.label}" saved; the scenario form now uses it`);
    if (!scnForm.id) scnForm.seedId = s.id; // a scenario being drafted picks up the seed just saved
    renderAll();
  };
  setSource(); refreshPreviews(); showProblems();
  const form = h('div', { class: 'form-grid' },
    h('div', { class: 'field' }, h('label', {}, 'Seed name'), name),
    h('div', { class: 'field' }, h('label', {}, 'Year'), year),
    h('div', { class: 'field full' }, h('label', {}, 'Helpers: start from an existing seed'), baseSel),
    h('div', { class: 'field full' }, h('div', { class: 'helper-row' },
      h('div', { class: 'field' }, h('label', {}, 'Raise yield by X % (multiplicative: (1+y)(1+X)−1)'), xMult),
      h('button', { class: 'btn', onClick: () => apply('mult') }, 'Apply'),
      h('span', { class: 'hint' }, 'e.g. 2028 +10% → OPV 70.5%')), prevMult),
    h('div', { class: 'field full' }, h('div', { class: 'helper-row' },
      h('div', { class: 'field' }, h('label', {}, 'Add X percentage points to every segment'), xAdd),
      h('button', { class: 'btn', onClick: () => apply('add') }, 'Apply'),
      h('span', { class: 'hint' }, 'e.g. 2028 +10 pp → OPV 65%')), prevAdd),
    h('div', { class: 'field full' }, h('label', {}, 'Yield change versus conventional seed, by farmer segment'), sourceLine, segGrid,
      h('span', { class: 'hint' }, 'Azahar’s seed_variants.yml: 2022 = 31.6 / 25.6 / 1.8 / −13.8; 2026 = 45 / 40 / 10 / −7; 2028 = 55 / 55 / 20 / −2 (%). Must be above −100% (no harvest).'), msgs),
    h('div', { class: 'btn-row full' }, h('button', { class: 'btn primary', onClick: save }, f.id ? 'Save changes' : 'Save seed'),
      h('button', { class: 'btn', onClick: () => { resetSeedForm(); markClean('seed'); renderSeedForm(); els.seedList.replaceChildren(seedList()); } }, 'Reset form')));
  els.seedForm.replaceChildren(form);
}

