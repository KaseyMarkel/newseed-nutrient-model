function startSubFrom(s) {
  subForm = JSON.parse(JSON.stringify(s));
  if (s.official) { subForm.id = null; subForm.label = s.label + ' (modified)'; }
  delete subForm.official;
  renderSubForm();
  els.subList.replaceChildren(subsidyList());
}
// A number field that accepts decimal commas, shows its own error, and calls set(value|NaN).
function numField(value, set, aria) {
  const inp = h('input', { type: 'text', inputmode: 'decimal', value: Number.isFinite(value) ? String(value) : '', 'aria-label': aria || '' });
  const err = h('span', { class: 'err-msg' });
  inp.addEventListener('input', () => {
    const v = parseNum(inp.value);
    const bad = !Number.isFinite(v);
    inp.classList.toggle('invalid', bad);
    err.textContent = bad ? (inp.value.trim() === '' ? 'Enter a number' : 'Not a number') : '';
    set(bad ? NaN : v);
  });
  return { inp, err };
}
function renderSubForm() {
  if (!subForm) { els.subForm.replaceChildren(h('div', { class: 'note info' }, 'Pick a regime above and press "Start from" to create a variant: change what New Seed pays per manzana and the price farmers pay for biofortified seed.')); return; }
  const f = subForm;
  f.seed_cost_conventional = f.seed_cost_conventional || { OPV_Criollo: 61, Low: 305, Mid: 488, High: 976 };
  f.seed_cost_biofortified = f.seed_cost_biofortified || { OPV_Criollo: 305, Low: 305, Mid: 305, High: 305 };
  if (f.bio_cost_no_subsidy_per_mz == null) f.bio_cost_no_subsidy_per_mz = 547;
  const msgs = h('div', { class: 'warn-list full' });
  const check = () => {
    const p = subsidyProblems(f);
    msgs.replaceChildren(...p.errors.map(e => h('div', { class: 'note err' }, e)), ...p.warnings.map(w => h('div', { class: 'note' }, w)));
    return p;
  };
  const name = h('input', { type: 'text', value: f.label || '', maxlength: 80, onInput: e => { f.label = e.target.value; } });
  const ns = numField(f.newseed_subsidy_per_mz, v => { f.newseed_subsidy_per_mz = v; check(); }, 'New Seed subsidy');
  const nosub = numField(f.bio_cost_no_subsidy_per_mz, v => { f.bio_cost_no_subsidy_per_mz = v; check(); }, 'Unsubsidised price');
  const bioFields = SEGMENTS.map(k => numField(f.seed_cost_biofortified[k], v => { f.seed_cost_biofortified[k] = v; check(); }, `Biofortified price ${k}`));
  const bioAll = numField(Object.values(f.seed_cost_biofortified)[0], v => {
    SEGMENTS.forEach((k, i) => { f.seed_cost_biofortified[k] = v; bioFields[i].inp.value = Number.isFinite(v) ? String(v) : bioAll.inp.value; bioFields[i].inp.classList.toggle('invalid', !Number.isFinite(v)); });
    check();
  }, 'Biofortified price, all segments');
  const bioGrid = h('div', { class: 'seg-grid' }, SEGMENTS.map((k, i) => h('div', { class: 'field' }, h('label', {}, SEG_LABELS[k]), bioFields[i].inp, bioFields[i].err)));
  const convGrid = h('div', { class: 'seg-grid' }, SEGMENTS.map(k => { const c = numField(f.seed_cost_conventional[k], v => { f.seed_cost_conventional[k] = v; check(); }, `Conventional price ${k}`); return h('div', { class: 'field' }, h('label', {}, SEG_LABELS[k]), c.inp, c.err); }));
  const fill = h('button', { class: 'btn small', onClick: () => {
    if (!Number.isFinite(f.newseed_subsidy_per_mz) || !Number.isFinite(f.bio_cost_no_subsidy_per_mz)) { toast('Enter the subsidy and the unsubsidised price first'); return; }
    const v = Math.max(0, f.bio_cost_no_subsidy_per_mz - f.newseed_subsidy_per_mz);
    SEGMENTS.forEach((k, i) => { f.seed_cost_biofortified[k] = v; bioFields[i].inp.value = String(v); bioFields[i].inp.classList.remove('invalid'); bioFields[i].err.textContent = ''; });
    bioAll.inp.value = String(v); check();
  } }, 'Farmer price = unsubsidised − New Seed subsidy');
  const save = () => {
    const label = (f.label || '').trim();
    if (!label) { toast('Give the regime a name'); return; }
    const clash = allSubsidies(defaults).find(s => s.id !== f.id && s.label.trim().toLowerCase() === label.toLowerCase());
    if (clash) { toast(`A regime called "${clash.label}" already exists; choose another name`); return; }
    if (check().errors.length) { toast('Fix the values marked in red first'); return; }
    const cur = defaults.params.newseed_subsidy_current_per_mz || 242;
    const s = saveSubsidy({ ...f, label, reduction_pct: Math.round((1 - f.newseed_subsidy_per_mz / cur) * 100) });
    subForm = JSON.parse(JSON.stringify(s)); // edit a copy, never the stored object
    markClean('sub');
    toast(`Subsidy regime "${s.label}" saved`); renderAll();
  };
  check();
  els.subForm.replaceChildren(h('div', { class: 'form-grid' },
    h('div', { class: 'field full' }, h('label', {}, 'Regime name'), name),
    h('div', { class: 'field' }, h('label', {}, 'New Seed subsidy (GTQ per manzana)'), ns.inp, ns.err, h('span', { class: 'hint' }, 'Current regime: 242 = 547 − 305')),
    h('div', { class: 'field' }, h('label', {}, 'Unsubsidised biofortified seed price (GTQ/mz)'), nosub.inp, nosub.err),
    h('div', { class: 'field full' }, h('label', {}, 'Price farmers pay for biofortified seed (GTQ/mz), all segments'), bioAll.inp, bioAll.err, h('div', {}, fill)),
    h('div', { class: 'field full' }, h('label', {}, 'Biofortified seed price by segment (GTQ/mz)'), bioGrid),
    h('div', { class: 'field full' }, h('label', {}, 'Conventional seed price by segment (GTQ/mz)'), convGrid),
    msgs,
    h('div', { class: 'btn-row full' }, h('button', { class: 'btn primary', onClick: save }, f.id ? 'Save changes' : 'Save regime'),
      h('button', { class: 'btn', onClick: () => { subForm = null; markClean('sub'); renderSubForm(); els.subList.replaceChildren(subsidyList()); } }, 'Cancel'))));
}

